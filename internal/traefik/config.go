// Package traefik generates the Traefik configuration from Dockfly's state
// and supervises the Traefik process.
package traefik

import (
	"fmt"
	"maps"
	"net"
	"net/url"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/dockfly/dockfly/internal/store"
)

const (
	CertResolver = "letsencrypt"

	mwRedirectHTTPS = "dockfly-redirect-https"
	mwHSTS          = "dockfly-hsts"
	mwCompress      = "dockfly-compress"
	// MwDeny denies everything: it is used when a route should be protected
	// by an access list that no longer exists (it must never be left open).
	MwDeny           = "dockfly-deny"
	transportNoCheck = "dockfly-insecure"

	dynamicFile = "dockfly.yml"
)

// Options holds Traefik's static configuration.
type Options struct {
	DataDir     string // persistent directory (/data)
	HTTPAddr    string // ":80"
	HTTPSAddr   string // ":443"
	ACMEEmail   string
	ACMEStaging bool
	DockerNet   string // network where Traefik looks for containers with labels
	LogLevel    string
	// Streams are the TCP/UDP ports Traefik listens on. They are static
	// configuration: changing them requires restarting Traefik.
	Streams []StreamPort
	// DNSProviders are the providers (lego codes) that use the DNS-01
	// challenge; each one becomes a "dns-<provider>" resolver.
	DNSProviders []string
	// TrustedProxies are the ranges (CIDR or IP) of the proxies sitting in
	// front of Traefik (Cloudflare, a load balancer…): only their
	// X-Forwarded-* headers are accepted, so access lists see the real IP.
	TrustedProxies []string
}

// DNSResolver is the name of a DNS provider's ACME resolver.
func DNSResolver(provider string) string { return "dns-" + provider }

type StreamPort struct {
	Protocol string // tcp | udp
	Port     int
}

// EntryPoint is the name of a stream's entry point.
func (p StreamPort) EntryPoint() string { return p.Protocol + "-" + strconv.Itoa(p.Port) }

func (o Options) DynamicDir() string { return filepath.Join(o.DataDir, "traefik", "dynamic") }
func (o Options) StaticFile() string { return filepath.Join(o.DataDir, "traefik", "traefik.yml") }
func (o Options) ACMEFile() string   { return filepath.Join(o.DataDir, "traefik", "acme.json") }

// WriteStatic writes traefik.yml. Traefik only reads it at startup.
func WriteStatic(o Options) error {
	if err := os.MkdirAll(o.DynamicDir(), 0o755); err != nil {
		return err
	}

	acme := map[string]any{
		"storage":       o.ACMEFile(),
		"httpChallenge": map[string]any{"entryPoint": "web"},
	}
	if o.ACMEEmail != "" {
		acme["email"] = o.ACMEEmail
	}
	if o.ACMEStaging {
		acme["caServer"] = "https://acme-staging-v02.api.letsencrypt.org/directory"
	}

	providers := map[string]any{
		"file": map[string]any{"directory": o.DynamicDir(), "watch": true},
		// Applies the panel's changes almost instantly (the default is 2s).
		"providersThrottleDuration": "200ms",
	}
	// No Docker provider: every route is generated by Dockfly in the file
	// provider. With it, any container (an app, or whatever an image's labels
	// carry) could declare its own routers through traefik.* labels and take
	// over the traffic of any domain.

	resolvers := map[string]any{CertResolver: map[string]any{"acme": acme}}
	for _, p := range o.DNSProviders {
		dns := maps.Clone(acme)
		delete(dns, "httpChallenge")
		dns["dnsChallenge"] = map[string]any{
			"provider": p,
			// Public DNS: the server's own resolvers may still have the old
			// TXT record cached and delay validation.
			"resolvers": []string{"1.1.1.1:53", "8.8.8.8:53"},
		}
		resolvers[DNSResolver(p)] = map[string]any{"acme": dns}
	}

	cfg := map[string]any{
		"global": map[string]any{"checkNewVersion": false, "sendAnonymousUsage": false},
		// Per-router metrics for the traffic charts. Served on localhost
		// only: Dockfly is the one reading them.
		"metrics": map[string]any{"prometheus": map[string]any{
			"entryPoint":           metricsEntryPoint,
			"addRoutersLabels":     true,
			"addEntryPointsLabels": false,
			"addServicesLabels":    false,
			"buckets":              LatencyBuckets,
		}},
		// JSON: Dockfly parses it (Let's Encrypt errors) and rewrites it readable.
		"log":                   map[string]any{"level": o.LogLevel, "noColor": true, "format": "json"},
		"entryPoints":           entryPoints(o),
		"providers":             providers,
		"certificatesResolvers": resolvers,
	}
	return writeYAML(o.StaticFile(), cfg)
}

// MetricsAddr is where Traefik serves its metrics (for Dockfly only).
const MetricsAddr = "127.0.0.1:8082"

const metricsEntryPoint = "metrics"

// LatencyBuckets are the bounds (in seconds) of the latency histogram.
var LatencyBuckets = []float64{0.005, 0.01, 0.025, 0.05, 0.1, 0.25, 0.5, 1, 2.5, 5, 10}

func entryPoints(o Options) map[string]any {
	eps := map[string]any{
		"web":             entryPoint(o.HTTPAddr, o.TrustedProxies),
		"websecure":       entryPoint(o.HTTPSAddr, o.TrustedProxies),
		metricsEntryPoint: entryPoint(MetricsAddr, nil),
	}
	for _, p := range o.Streams {
		addr := ":" + strconv.Itoa(p.Port)
		if p.Protocol == "udp" {
			addr += "/udp"
		}
		eps[p.EntryPoint()] = map[string]any{"address": addr}
	}
	return eps
}

// entryPoint drops the headers that pose as other ones (X_Forwarded_For
// standing in for X-Forwarded-For), so a client cannot forge the headers
// Traefik manages on PHP, CGI or WSGI backends. With trustedIPs, Traefik
// honours the X-Forwarded-For arriving from those proxies.
func entryPoint(addr string, trustedIPs []string) map[string]any {
	ep := map[string]any{
		"address": addr,
		"http":    map[string]any{"aliasHeadersStrategy": "delete"},
	}
	if len(trustedIPs) > 0 {
		ep["forwardedHeaders"] = map[string]any{"trustedIPs": trustedIPs}
	}
	return ep
}

// Route is a routing entry: a set of domains that Traefik forwards to a
// URL. Proxy hosts and static sites are translated into routes.
type Route struct {
	Name          string // unique: it names the routers and the service
	Domains       []string
	URL           string
	PreserveHost  bool
	SkipTLSVerify bool
	SSL           bool
	ForceHTTPS    bool
	HSTS          bool
	Compress      bool
	// Extra middlewares (e.g. those of an access list), in order.
	Middlewares []string
	// PathPrefix limits the route to a part of the domain (a custom
	// location: "/api"); StripPrefix removes it before forwarding.
	PathPrefix  string
	StripPrefix bool
	// Redirect turns the route into a redirect (with no backend).
	Redirect *Redirect
	// The certificate's ACME resolver: "" = Let's Encrypt over HTTP,
	// NoResolver = use a custom certificate already loaded into Traefik.
	Resolver string
}

// NoResolver means the certificate is supplied by the user.
const NoResolver = "-"

// CertFile is a custom certificate written to disk.
type CertFile struct {
	Cert, Key string
}

// Dynamic is everything that goes into the dynamic configuration.
type Dynamic struct {
	Routes       []Route
	Middlewares  map[string]any // access lists
	Streams      []Stream
	Certificates []CertFile
}

type Redirect struct {
	Target       string // target URL, without a trailing slash
	Permanent    bool
	PreservePath bool
}

// ProxyHostRoute translates a proxy host. Returns ok=false if it is disabled.
func ProxyHostRoute(h *store.ProxyHost) (Route, bool) {
	if !h.Enabled || len(h.Domains) == 0 {
		return Route{}, false
	}
	return Route{
		Name:          "ph-" + strconv.FormatInt(h.ID, 10),
		Domains:       h.Domains,
		URL:           BackendURL(h),
		PreserveHost:  h.PreserveHost,
		SkipTLSVerify: h.ForwardScheme == "https" && h.SkipTLSVerify,
		SSL:           h.SSL,
		ForceHTTPS:    h.ForceHTTPS,
		HSTS:          h.HSTS,
	}, true
}

// SiteRoute translates a static site: they all point at Dockfly's static
// server, which picks the site by the Host header (hence it is preserved).
func SiteRoute(site *store.Site, staticURL string) (Route, bool) {
	if len(site.Domains) == 0 {
		return Route{}, false
	}
	return Route{
		Name:         "site-" + strconv.FormatInt(site.ID, 10),
		Domains:      site.Domains,
		URL:          staticURL,
		PreserveHost: true,
		SSL:          site.SSL,
		ForceHTTPS:   site.ForceHTTPS,
		HSTS:         site.HSTS,
		Compress:     true,
	}, true
}

// WriteDynamic regenerates the whole dynamic configuration. Traefik picks
// the change up on the fly, with no restart. extra are the additional
// middlewares (access lists) the routes may refer to.
func WriteDynamic(o Options, d Dynamic) error {
	data, err := RenderDynamic(d)
	if err != nil {
		return err
	}
	return WriteDynamicBytes(o, data)
}

// RenderDynamic generates the dynamic configuration (YAML), e.g. to send
// it to the agent of a remote server.
func RenderDynamic(d Dynamic) ([]byte, error) {
	cfg := BuildDynamic(d.Routes, d.Middlewares)
	streamConfig(d.Streams, cfg)
	if len(d.Certificates) > 0 {
		var list []map[string]string
		for _, c := range d.Certificates {
			list = append(list, map[string]string{"certFile": c.Cert, "keyFile": c.Key})
		}
		cfg["tls"] = map[string]any{"certificates": list}
	}
	data, err := yaml.Marshal(cfg)
	if err != nil {
		return nil, err
	}
	return append([]byte(generatedHeader), data...), nil
}

// WriteDynamicBytes writes an already generated dynamic configuration.
func WriteDynamicBytes(o Options, data []byte) error {
	return writeFile(filepath.Join(o.DynamicDir(), dynamicFile), data)
}

const generatedHeader = "# Generated by Dockfly. Do not edit: it is overwritten on every change.\n"

// BuildDynamic translates the routes into Traefik's dynamic configuration.
func BuildDynamic(routes []Route, extra map[string]any) map[string]any {
	routers := map[string]any{}
	services := map[string]any{}
	middlewares := map[string]any{
		mwRedirectHTTPS: map[string]any{
			"redirectScheme": map[string]any{"scheme": "https", "permanent": true},
		},
		mwHSTS: map[string]any{
			"headers": map[string]any{
				"stsSeconds":           31536000,
				"stsIncludeSubdomains": true,
				"stsPreload":           false,
			},
		},
		// gzip/brotli/zstd depending on what the browser accepts.
		mwCompress: map[string]any{"compress": map[string]any{}},
		// No real client has this IP: it denies everything.
		MwDeny: map[string]any{"ipAllowList": map[string]any{"sourceRange": []string{"255.255.255.255/32"}}},
	}
	for name, mw := range extra {
		middlewares[name] = mw
	}
	needsInsecure := false

	for _, rt := range routes {
		rule := hostRule(rt.Domains)
		if rt.PathPrefix != "" {
			rule = fmt.Sprintf("(%s) && PathPrefix(`%s`)", rule, rt.PathPrefix)
			if rt.StripPrefix {
				mw := rt.Name + "-strip"
				middlewares[mw] = map[string]any{"stripPrefix": map[string]any{"prefixes": []string{rt.PathPrefix}}}
				rt.Middlewares = append(slices.Clone(rt.Middlewares), mw)
			}
		}
		// Priority: as Traefik does by default, the longer the rule the more
		// it gets (a location beats its host, and /api/v2 beats /api).
		// Wildcards always stay below (≤ 202: paths are 200 characters at
		// most) the concrete hosts (≥ 1000): otherwise a long location of
		// *.domain.com would beat app.domain.com.
		priority := 1000 + len(rule)
		if hasWildcard(rt.Domains) {
			priority = 1
			if rt.PathPrefix != "" {
				priority = 2 + len(rt.PathPrefix)
			}
		}

		service := rt.Name
		if rt.Redirect != nil {
			// A redirect needs no backend: the internal noop service is
			// never actually used because the middleware answers first.
			service = "noop@internal"
			mw := rt.Name + "-redirect"
			replacement := rt.Redirect.Target
			if rt.Redirect.PreservePath {
				replacement += "${1}"
			}
			middlewares[mw] = map[string]any{"redirectRegex": map[string]any{
				"regex": `^https?://[^/]+(/.*)?$`, "replacement": replacement, "permanent": rt.Redirect.Permanent,
			}}
			rt.Middlewares = append(slices.Clone(rt.Middlewares), mw)
			rt.ForceHTTPS = false // the redirect already decides the target
		}

		svc := map[string]any{
			"servers":        []map[string]any{{"url": rt.URL}},
			"passHostHeader": rt.PreserveHost,
		}
		if rt.SkipTLSVerify {
			svc["serversTransport"] = transportNoCheck
			needsInsecure = true
		}
		if rt.Redirect == nil {
			services[rt.Name] = map[string]any{"loadBalancer": svc}
		}

		// Access control comes first: there is no point in compressing a
		// response that is going to be denied.
		common := slices.Clone(rt.Middlewares)
		if rt.Compress {
			common = append(common, mwCompress)
		}

		httpRouter := map[string]any{
			"rule":        rule,
			"entryPoints": []string{"web"},
			"service":     service,
		}
		httpMW := common
		if rt.SSL {
			secureMW := slices.Clone(common)
			if rt.HSTS {
				secureMW = append(secureMW, mwHSTS)
			}
			tls := map[string]any{}
			switch rt.Resolver {
			case NoResolver:
				// Traefik picks the custom certificate that covers the domain.
			case "":
				tls["certResolver"] = CertResolver
			default:
				tls["certResolver"] = rt.Resolver
			}
			// With wildcards the rule (HostRegexp) does not say which
			// certificate to ask for: state it explicitly.
			if hasWildcard(rt.Domains) && tls["certResolver"] != nil {
				tls["domains"] = []map[string]any{{"main": rt.Domains[0], "sans": rt.Domains[1:]}}
			}
			secure := map[string]any{
				"rule":        rule,
				"entryPoints": []string{"websecure"},
				"service":     service,
				"tls":         tls,
			}
			if priority > 0 {
				secure["priority"] = priority
			}
			if len(secureMW) > 0 {
				secure["middlewares"] = secureMW
			}
			routers[rt.Name+"-secure"] = secure

			if rt.ForceHTTPS {
				// When redirecting, compressing makes no sense.
				httpMW = []string{mwRedirectHTTPS}
			}
		}
		if len(httpMW) > 0 {
			httpRouter["middlewares"] = httpMW
		}
		if priority > 0 {
			// HostRegexp is a long rule: without this it would outrank the
			// concrete hosts of the same domain and swallow them.
			httpRouter["priority"] = priority
		}
		routers[rt.Name] = httpRouter
	}

	// Traefik rejects empty sections, so only the ones with content go in.
	httpCfg := map[string]any{"middlewares": middlewares}
	if len(routers) > 0 {
		httpCfg["routers"] = routers
	}
	if len(services) > 0 {
		httpCfg["services"] = services
	}
	if needsInsecure {
		httpCfg["serversTransports"] = map[string]any{
			transportNoCheck: map[string]any{"insecureSkipVerify": true},
		}
	}
	return map[string]any{"http": httpCfg}
}

// BackendURL builds the URL of the target service.
func BackendURL(h *store.ProxyHost) string {
	u := url.URL{
		Scheme: h.ForwardScheme,
		Host:   net.JoinHostPort(h.ForwardHost, strconv.Itoa(h.ForwardPort)),
	}
	return u.String()
}

// LocationURL is the target of a custom location.
func LocationURL(l store.ProxyLocation) string {
	u := url.URL{Scheme: l.ForwardScheme, Host: net.JoinHostPort(l.ForwardHost, strconv.Itoa(l.ForwardPort))}
	return u.String()
}

func hostRule(domains []string) string {
	parts := make([]string, len(domains))
	for i, d := range domains {
		if rest, ok := strings.CutPrefix(d, "*."); ok {
			// A wildcard covers a single level, as certificates do.
			parts[i] = fmt.Sprintf("HostRegexp(`^[a-z0-9-]+\\.%s$`)", strings.ReplaceAll(rest, ".", `\.`))
			continue
		}
		parts[i] = fmt.Sprintf("Host(`%s`)", d)
	}
	return strings.Join(parts, " || ")
}

func hasWildcard(domains []string) bool {
	return slices.ContainsFunc(domains, func(d string) bool { return strings.HasPrefix(d, "*.") })
}

// writeYAML writes atomically (temporary file + rename) so that Traefik
// never reads a half-written file.
func writeYAML(path string, v any) error {
	data, err := yaml.Marshal(v)
	if err != nil {
		return err
	}
	return writeFile(path, append([]byte(generatedHeader), data...))
}

// writeFile writes atomically: Traefik never reads a half-written file.
func writeFile(path string, data []byte) error {

	tmp, err := os.CreateTemp(filepath.Dir(path), ".tmp-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Chmod(tmp.Name(), 0o644); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), path)
}

// AccessListMiddlewares generates an access list's middlewares: allowed
// IPs and/or username and password. Returns their names, in order.
func AccessListMiddlewares(id int64, allowIPs []string, users map[string]string, into map[string]any) []string {
	var names []string
	prefix := "acl-" + strconv.FormatInt(id, 10)
	if len(allowIPs) > 0 {
		into[prefix+"-ip"] = map[string]any{"ipAllowList": map[string]any{"sourceRange": allowIPs}}
		names = append(names, prefix+"-ip")
	}
	if len(users) > 0 {
		list := make([]string, 0, len(users))
		for u, hash := range users {
			list = append(list, u+":"+hash)
		}
		slices.Sort(list)
		into[prefix+"-auth"] = map[string]any{"basicAuth": map[string]any{
			"users": list, "realm": "Dockfly",
			// The app behind it does not need (and must not see) the password.
			"removeHeader": true,
		}}
		names = append(names, prefix+"-auth")
	}
	return names
}

// Stream is the dynamic part of a stream: where it forwards to.
type Stream struct {
	Name    string
	Port    StreamPort
	Address string // target host:port
}

// streamConfig adds the TCP/UDP routers and services of the streams.
func streamConfig(streams []Stream, into map[string]any) {
	sections := map[string]map[string]map[string]any{}
	for _, st := range streams {
		proto := st.Port.Protocol
		if sections[proto] == nil {
			sections[proto] = map[string]map[string]any{"routers": {}, "services": {}}
		}
		router := map[string]any{"entryPoints": []string{st.Port.EntryPoint()}, "service": st.Name}
		if proto == "tcp" {
			// Without TLS, HostSNI(`*`) is the only rule possible: all the port's traffic.
			router["rule"] = "HostSNI(`*`)"
		}
		sections[proto]["routers"][st.Name] = router
		sections[proto]["services"][st.Name] = map[string]any{
			"loadBalancer": map[string]any{"servers": []map[string]any{{"address": st.Address}}},
		}
	}
	for proto, sec := range sections {
		into[proto] = map[string]any{"routers": sec["routers"], "services": sec["services"]}
	}
}
